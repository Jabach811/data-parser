const path = require("path");
const { chromium } = require("playwright");
const ROOT = path.resolve(__dirname, "..");
const APP = require("url").pathToFileURL(path.join(ROOT, "Workbook Studio.html")).href;
const V = (p) => path.join(ROOT, "Test Samples", "Vendor Files", p);
const M = (p) => path.join(ROOT, "Test Samples", "Mapping Files", p);
(async () => {
  const browser = await chromium.launch();
  const ctx = await browser.newContext({ acceptDownloads: true });
  const page = await ctx.newPage();
  page.on("console", (m) => { if (m.type() === "error") console.log("CONSOLE", m.text().slice(0, 200)); });
  page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
  await page.goto(APP);
  await page.fill("#caseNumberInput", "AB1234567890");
  await page.fill("#planNameInput", "Test Plan");
  await page.setInputFiles("#fileInput", [V(process.argv[2] || "fidelity/FIDELITY_summary_tabs_mock.txt")]);
  await page.waitForSelector('#loadingBox[data-loading-state="complete"]', { timeout: 30000 });
  console.log("loading:", await page.textContent("#loadingTitle"), "|", await page.textContent("#loadingNote"));
  console.log("error:", (await page.textContent("#errorText")).trim().slice(0, 300));
  console.log("detected:", (await page.textContent("#dpcDetected")).trim());
  console.log("source:", await page.inputValue("#dataSourceSelect"));
  await page.setInputFiles("#mappingFileInput", [M(process.argv[3] || "v01-matched.xlsx")]);
  await page.waitForFunction(() => !document.getElementById("mappingImportBtn").classList.contains("is-validating"));
  await page.waitForTimeout(500);
  console.log("mapping:", await page.textContent("#mappingImportBtn strong"), "|", await page.textContent("#mappingImportBtn em"));
  console.log("comparisonStatus:", await page.getAttribute("#comparisonStatus", "class"), (await page.textContent("#comparisonStatus")).trim().slice(0, 200));
  console.log("vpHold hidden:", await page.$eval("#vpHold", (e) => e.hidden), (await page.textContent("#vpHold")).trim().slice(0, 200));
  console.log("export disabled:", await page.$eval("#exportWorkbookBtn", (e) => e.disabled));
  await page.click("#exportWorkbookBtn");
  await page.waitForTimeout(800);
  const conv = await page.$("#dpcConvDialog[open]");
  console.log("conv open:", !!conv);
  if (conv) console.log(await conv.innerText());
  const exp = await page.$("#dpcExportDialog[open]");
  console.log("export dialog open:", !!exp);
  if (exp) console.log(await exp.innerText());
  await browser.close();
})().catch((e) => { console.error(e); process.exit(1); });
